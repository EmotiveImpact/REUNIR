"""Writes platform/apps/web/src/phone-type.css: on phones, text set below 12px is raised to a readable size.

Every font-size that can apply at phone width is repeated, in stylesheet import order and with the same
selector, inside a phone-width media query. Sizes under 12px are raised (9px to 11px, 10px to 12px, 11px to 12.5px);
larger sizes are repeated unchanged so the original cascade order still decides which rule wins. Desktop is untouched.

Run `python3 scripts/phone_type.py` after changing a font size; `--check` fails when the file is out of date.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "platform/apps/web/src"
OUT = WEB / "phone-type.css"
PHONE = 760


def phone_size(px: float) -> float:
    return px if px >= 12 or px == 0 else max(11.0, min(12.5, px + 2))


def parse(css: str):
    """Yields (media conditions, selector, body) for every style rule, descending into @media blocks."""
    i, n = 0, len(css)
    stack = []  # media preludes, or None for a block we skip
    while i < n:
        j = css.find("{", i)
        k = css.find("}", i)
        if k != -1 and (j == -1 or k < j):
            if stack:
                stack.pop()
            i = k + 1
            continue
        if j == -1:
            break
        prelude = css[i:j].strip()
        if prelude.startswith("@"):
            stack.append(prelude if prelude.startswith("@media") else None)
            i = j + 1
            continue
        end = css.find("}", j)
        if None not in stack:
            yield tuple(stack), prelude, css[j + 1:end]
        i = end + 1


def phone_condition(media: tuple):
    """The media query to repeat a rule under at phone width, or None when it never applies to a phone."""
    widths = [PHONE]
    extra = []
    for m in media:
        cond = m[len("@media"):].strip()
        if "min-width" in cond:
            return None
        for part in re.split(r"\s+and\s+", cond):
            w = re.fullmatch(r"\(\s*max-width\s*:\s*(\d+)px\s*\)", part.strip())
            if w:
                widths.append(int(w.group(1)))
            elif part.strip():
                extra.append(part.strip())
    return " and ".join([f"(max-width:{min(widths)}px)"] + extra)


def fmt(px: float) -> str:
    return f"{px:g}px"


def generate() -> str:
    main = (WEB / "main.tsx").read_text()
    sheets = [s for s in re.findall(r"import '\./([\w-]+\.css)';", main) if s != OUT.name]
    blocks = []
    for sheet in sheets:
        css = re.sub(r"/\*.*?\*/", "", (WEB / sheet).read_text(), flags=re.S)
        for media, selector, body in parse(css):
            sizes = re.findall(r"font-size\s*:\s*([^;}!]+?)\s*(!important)?\s*(?:;|$)", body)
            if not sizes:
                continue
            cond = phone_condition(media)
            if cond is None:
                continue
            value, important = sizes[-1]
            px = re.fullmatch(r"([\d.]+)px", value)
            size = fmt(phone_size(float(px.group(1)))) if px else value
            decl = f"font-size:{size}{' !important' if important else ''}"
            if blocks and blocks[-1][0] == cond:
                blocks[-1][1].append(f"{selector}{{{decl}}}")
            else:
                blocks.append((cond, [f"{selector}{{{decl}}}"]))
    head = "/* Generated by scripts/phone_type.py: readable text sizes on phones. Do not edit by hand. */\n"
    return head + "".join(f"@media{c}{{{''.join(r)}}}\n" for c, r in blocks)


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else "phone-type.css is out of date: run python3 scripts/phone_type.py")
    OUT.write_text(text)
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
